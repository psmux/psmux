//
// tmux hands the expanded status string to libc strftime. psmux formatted it
// with chrono until chrono was flagged unmaintained (RUSTSEC-2026-0543); the
// expected values below were recorded from chrono 0.4.45 so the replacement
// prints exactly what psmux printed before, byte for byte, including the
// strings chrono refused (None: the caller then keeps the unformatted text).
// Registered from src/format.rs.

use super::strftime_fixed_for_test as fmt_at;

